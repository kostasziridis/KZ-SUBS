#!/usr/bin/env python3
"""Put Localizable.xcstrings back in agreement with the code.

Building with SWIFT_EMIT_LOC_STRINGS=YES makes Xcode rewrite the catalogue in the
source tree, and it does not do it well: it writes a second copy of every key that
carries a number (`%@ subtitles` beside the real `%lld subtitles`), marks the real
one stale, and drops the keys that are deliberately left untranslated. The strings
the app actually looks up at runtime are the compiler's, which are the ones in the
`.stringsdata` files - so those are taken as the truth here.

    python3 Tools/tidy-string-catalog.py <derived-data-path>

Existing translations are kept. Anything the compiler no longer emits is dropped,
and anything new is listed so it can be translated.
"""
import json, pathlib, sys

# Brand names, format-only strings and numerals: nothing to translate, and marking
# them so keeps them out of the "untranslated" report for good.
VERBATIM = {
    '%@ · %@', '%@ — %@', '%lld', '%lld%%', '3', '4', '5', '6',
    'KZ', 'SUBS', 'kziridis.com', 'Mono', '~250 MB', '~630 MB', '~950 MB',
}

CATALOGUE = pathlib.Path(__file__).resolve().parent.parent / "Sources/Resources/Localizable.xcstrings"


def compiler_keys(derived_data: pathlib.Path) -> set[str]:
    keys = set()
    for path in derived_data.rglob("*.stringsdata"):
        if "KZSubs.build" not in str(path):
            continue  # the package's own strings are not ours to translate
        data = json.loads(path.read_text())
        # Only this catalogue's own table: Info.plist keys belong to InfoPlist.xcstrings
        # and would otherwise be reported as missing translations here forever.
        for table, entries in data.get("tables", {}).items():
            if table != "Localizable":
                continue
            keys.update(entry["key"] for entry in entries)
    return keys


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2

    keys = compiler_keys(pathlib.Path(sys.argv[1]))
    if not keys:
        print("No .stringsdata found - build with SWIFT_EMIT_LOC_STRINGS=YES first.")
        return 1

    catalogue = json.loads(CATALOGUE.read_text())
    previous = catalogue["strings"]

    tidied, untranslated = {}, []
    for key in sorted(keys):
        if key in VERBATIM:
            tidied[key] = {"shouldTranslate": False}
            continue

        old = previous.get(key, {})
        localisations = old.get("localizations", {})
        if "el" in localisations:
            entry = {"localizations": localisations}
            if "comment" in old:
                entry["comment"] = old["comment"]
                entry["isCommentAutoGenerated"] = True
            tidied[key] = entry
        else:
            tidied[key] = {}
            untranslated.append(key)

    catalogue["strings"] = tidied
    CATALOGUE.write_text(json.dumps(catalogue, ensure_ascii=False, indent=2) + "\n")

    dropped = len(set(previous) - keys)
    print(f"{len(tidied)} keys, {dropped} dropped as no longer in the code")
    if untranslated:
        print("\nNeeds Greek:")
        for key in untranslated:
            print("  ", key)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
